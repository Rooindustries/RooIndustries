import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { createRequire } from "node:module";
import { performance } from "node:perf_hooks";

const root = process.cwd();
const studio = path.join(root, "rooindustries");
const require = createRequire(path.join(studio, "package.json"));
const evidence = [];
for (const directory of [root, studio]) {
  const manifest = JSON.parse(fs.readFileSync(path.join(directory, "package.json")));
  const lock = JSON.parse(fs.readFileSync(path.join(directory, "package-lock.json")));
  for (const field of ["dependencies", "devDependencies"]) assert.deepEqual(lock.packages[""][field], manifest[field]);
  evidence.push({ check: "manifest-lock-consistency", directory: path.relative(root, directory) || "root", directDependencies: Object.keys(manifest.dependencies).length });
}
const studioLock = JSON.parse(fs.readFileSync(path.join(studio, "package-lock.json")));
const maintained = /\/(?:adm-zip|baseline-browser-mapping|brace-expansion|browserslist|dompurify|js-yaml|markdown-it|nanoid|postcss|smol-toml|tar|undici)$/;
const installed = [];
for (const [location, entry] of Object.entries(studioLock.packages)) {
  if (!maintained.test(location)) continue;
  const actual = JSON.parse(fs.readFileSync(path.join(studio, location, "package.json")));
  assert.equal(actual.version, entry.version, location);
  installed.push({ location, version: actual.version });
}
evidence.push({ check: "studio-installed-lock-consistency", maintainedCopies: installed });
const expansion = require("brace-expansion");
assert.deepEqual(expansion("a{b,c}d"), ["abd", "acd"]);
const started = performance.now();
const bounded = expansion("{a}" + "}".repeat(128000) + ",z}");
assert.ok(Array.isArray(bounded));
const elapsedMs = performance.now() - started;
assert.ok(elapsedMs < 5000);
evidence.push({ check: "brace-expansion-documented-boundary", version: require("brace-expansion/package.json").version, literalClosingBraces: 128000, elapsedMs, outputs: bounded.length });
const toml = require("smol-toml");
assert.throws(() => toml.parse("a=[1 #"));
assert.deepEqual(toml.parse("name='fixture'\ncount=101"), { name: "fixture", count: 101 });
evidence.push({ check: "smol-toml-eof-comment", bytes: 6, rejected: true });
const yaml = require("js-yaml");
assert.deepEqual(yaml.safeLoad("name: fixture\nitems: [a, b]"), { name: "fixture", items: ["a", "b"] });
const Zip = require("adm-zip");
const archive = new Zip();
archive.addFile("fixture.txt", Buffer.from("isolated tooling fixture"));
assert.equal(new Zip(archive.toBuffer()).readAsText("fixture.txt"), "isolated tooling fixture");
const markdown = require("markdown-it")({ linkify: true });
assert.match(markdown.render("https://example.invalid"), /href="https:\/\/example\.invalid"/);
const postcss = require("postcss");
assert.match(postcss([]).process("a { color: red }", { from: undefined, map: false }).css, /color: red/);
const browserslist = require("browserslist");
assert.ok(browserslist(["last 1 chrome version"]).length > 0);
evidence.push({ check: "patched-parser-archive-build-apis", packages: ["js-yaml", "adm-zip", "markdown-it", "postcss", "browserslist"] });
const { JSDOM } = require("jsdom");
const { window } = new JSDOM('<div id="root"><section id="wrap"><img onerror="bad()"></section></div>');
const purify = require("dompurify")(window);
const img = window.document.querySelector("img");
purify.addHook("afterSanitizeElements", node => { if (node.id === "wrap") node.remove(); });
purify.sanitize(window.document.getElementById("root"), { IN_PLACE: true });
assert.equal(img.hasAttribute("onerror"), false);
window.close();
evidence.push({ check: "dompurify-detached-subtree-handler", version: purify.version, retainedHandler: false, standIn: "jsdom DOM; inspects attribute removal, does not claim browser event execution" });
const { prepareConfig } = await import(path.join(studio, "node_modules/@sanity/codegen/dist/utils/config.js"));
const { findQueriesInPath } = await import(path.join(studio, "node_modules/@sanity/codegen/dist/typescript/findQueriesInPath.js"));
const config = prepareConfig();
assert.equal(config.path, "./src/**/*.{ts,tsx,js,jsx}");
const scan = findQueriesInPath({ path: config.path });
const schemaScan = findQueriesInPath({ path: "./rooindustries/schemaTypes/**/*.{js,jsx}" });
assert.ok(scan.files.length > 0);
assert.ok(schemaScan.files.length > 0);
assert.ok(!fs.existsSync(path.join(studio, "sanity-typegen.json")));
assert.doesNotMatch(fs.readFileSync(path.join(studio, "sanity.cli.js"), "utf8"), /typegen\s*:/);
evidence.push({ check: "actual-codegen-fixed-pattern-reachability", defaultPattern: config.path, sourceFilesMatched: scan.files.length, schemaFilesMatched: schemaScan.files.length, depthOfDefaultBraceGroup: 1, configurableUntrustedPatterns: false, scope: "current checked-in CLI config and normal Studio startup; arbitrary future operator typegen patterns remain vulnerable" });
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "roo-tooling-dependency-"));
fs.writeFileSync(path.join(scratch, "scope.json"), JSON.stringify(evidence, null, 2));
const artifact = path.resolve("test-results/tooling-dependencies.json");
fs.mkdirSync(path.dirname(artifact), { recursive: true });
fs.writeFileSync(artifact, JSON.stringify({ passed: true, evidence }, null, 2) + "\n");
console.log(JSON.stringify({ passed: true, checks: evidence.length, artifact }));
